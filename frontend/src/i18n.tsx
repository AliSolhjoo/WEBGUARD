const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    try { return localStorage.getItem('webguard-language') === 'fa' ? 'fa' : 'en' }
    catch { return 'en' }
  })

  const setLanguage = useCallback((next: Language) => setLanguageState(next), [])
  const t = useCallback((value: string) => language === 'fa' ? (fa[value] ?? value) : value, [language])

  useEffect(() => {
    try { localStorage.setItem('webguard-language', language) } catch { /* storage can be unavailable in private contexts */ }
    document.documentElement.lang = language
    document.documentElement.dir = language === 'fa' ? 'rtl' : 'ltr'
    document.title = language === 'fa' ? 'WEBGUARD — سامانه ارزیابی امنیت' : 'WEBGUARD — Security Assessment Platform'
    const description = document.querySelector<HTMLMetaElement>('meta[name="description"]')
    if (description) description.content = language === 'fa'
      ? 'WEBGUARD — سامانه ارزیابی امنیت وب، مدیریت دارایی‌های تأییدشده و یافته‌های امنیتی مستند.'
      : 'WEBGUARD — authorized passive web security assessment, verified asset inventory, and evidence-backed security findings.'
  }, [language])

  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
